#!/bin/bash
# Build esphome/secrets.yaml (next to this repo's configs) from the 600-mode files in ~/.config/homelab. Never prints values.
# The indoor unit uses the original keys; the outdoor unit has its own, so they can be
# revoked on their own if it's stolen.
OUT="$(cd "$(dirname "$0")/.." && pwd)/esphome/secrets.yaml"
set -e; cd ~/.config/homelab; umask 077
r(){ [ -f "$1" ] && cat "$1" || echo -n "$2"; }
# HTTP Basic auth header for InfluxDB (kept out of the URL, which ESPHome logs on errors)
auth(){ echo -n "Basic $(printf '%s:%s' "$1" "$(cat "$2")" | base64)"; }
cat > "$OUT" <<Y
# Generated by bin/make_secrets.sh - edit the source files, not this.
wifi_ssid: "$(r wifi_ssid PLACEHOLDER_SSID)"
wifi_password: "$(r wifi_password placeholder-password)"
influx_host: "$(cat ha_host)"   # InfluxDB add-on runs on the HA host

# noise-indoor
indoor_api_key: "$(cat esphome_api_key)"
indoor_ota_password: "$(cat ota_password)"
indoor_influx_auth: "$(auth esp influx_esp_password)"

# noise-outdoor
outdoor_api_key: "$(cat outdoor_esphome_api_key)"
outdoor_ota_password: "$(cat outdoor_ota_password)"
outdoor_influx_auth: "$(auth esp_outdoor influx_esp_outdoor_password)"
Y
echo "secrets.yaml written ($( [ -f wifi_ssid ] && echo real || echo placeholder ) Wi-Fi)"
